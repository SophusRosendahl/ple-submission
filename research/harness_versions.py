"""Table of every recorded run with the harness version, commit and files hash that produced it.

  python3 research/harness_versions.py            # markdown table
  python3 research/harness_versions.py --write docs/harness-versions.md   # with the notes below

A version label alone is not enough: run-019 (Neon, "rung 1 v1") ran after patch_pi.py was added, run-017 (Flash, also
"rung 1 v1") before it. The commit and the files hash tell them apart; runs recorded before the hash existed show none.
"""
import argparse
import pathlib

import tracker

NOTES = """
## What each version is

| Version | What it is | Changed from the one before |
|---|---|---|
| rung 0 v1 to v4 | one model call, files as text | invalid runs (see the tracker); images, token budget |
| rung 0 v5 | one call, images attached once, reasoning effort low | output cap and effort chosen from the failures of v1 to v4 |
| rung 1 v1 | Pi agent loop, all files and drawings in the first message, tools write/edit/bash | first loop. Neon's first run (run-018) was invalid; its rerun (run-019) used `patch_pi.py`, Flash's run-017 did not |
| rung 1 v2 | v1 plus the input guard | started on the VM, cancelled after 16 minutes, never recorded |
| rung 1 v3 | v2 plus a 20-call budget guard | |
| rung 2 v1 | Pi loop, read tool, data not in the first message, requirements and checks requested, 40-call budget | |
| rung 2 v2 | rung 2 v1 plus the instruction to batch independent tool calls in one reply (several reads at once, several commands in one bash call) | one change: the batching line, and \"one by one\" reworded to \"several at once if you like\" |
| environment audit v1 | read-only listing of what a model can see in the task container, no model calls | a diagnostic, not a measurement |

Where to look: `harnesses/<entry>/VERSION` is the label; `harness.version`, `harness.commit` and `harness.files_sha256`
are in every run record (`research/runs.jsonl`); the harness also logs `pi: VERSION {...}` at the start of each task.
"""


def table():
    rows = ["| Run | Version | Model | Commit | Files hash | Valid |", "|---|---|---|---|---|---|"]
    for r in tracker.load_runs():
        h = r.get("harness") or {}
        valid = "no" if r.get("validity") or r.get("invalid") else "yes"
        rows.append(f"| {r['run_id']} | {tracker.harness_version(r) or '?'} | {(h.get('model') or '?').replace('google-cloud/', '')} "
                    f"| {h.get('commit') or '?'} | {h.get('files_sha256') or 'not recorded'} | {valid} |")
    return "\n".join(rows)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--write")
    a = ap.parse_args()
    text = table()
    if a.write:
        pathlib.Path(a.write).write_text("# Harness versions\n\nGenerated by `research/harness_versions.py`.\n\n" + text + "\n" + NOTES, encoding="utf-8")
        print("wrote", a.write)
    else:
        print(text)
