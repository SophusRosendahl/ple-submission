"""Results by harness version and model, for the write-up: pass rate, mean score, how runs failed, effort.

  python3 research/rung_summary.py [--model gemini-4-neon] [--write docs/ladder-results.md]

Only valid runs on one task are summarised (invalid runs, diagnostics and the organizers' reference are left out).
A run "passed the gates" when the grader's exec_status is OK (schema, clash and connectivity gates all passed).
"""
import argparse
import collections
import pathlib
import statistics as st

import check_table
import costs
import tracker

# whether the agent could run ifcopenshell in that version (rung 0 has no tools at all)
IFC_ALLOWED = {"rung 0 v5": "no tools", "rung 1 v1": "yes", "rung 1 v3": "yes", "rung 2 v1": "yes",
               "rung 1 v4": "no (blocked)", "rung 2 v2": "no (blocked)", "rung 2 v3": "no (blocked)"}
ORDER = ["rung 0 v5", "rung 1 v1", "rung 1 v3", "rung 2 v1", "rung 1 v4", "rung 2 v2", "rung 2 v3"]


def rows(model):
    groups = collections.defaultdict(list)
    for r in tracker.load_runs():
        v = tracker.harness_version(r)
        if v not in IFC_ALLOWED or tracker.invalid_reason(r) or model not in (r["harness"].get("model") or ""):
            continue
        t = next(iter(r["tasks"].values()))
        groups[v].append((r, t))
    return groups


def table(model):
    out = ["| Version | ifcopenshell for the agent | runs | passed the gates | mean score | how the others failed | calls (mean) | prompt tokens (mean) | new, uncached (mean) | minutes (mean) |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for v in ORDER:
        g = rows(model).get(v)
        if not g:
            continue
        scores = [t["score"] for _, t in g]
        def exec_status(r):
            try:
                return check_table._json(check_table.verifier_dir(r["run_id"]) / "metrics.json").get("exec_status") or "?"
            except Exception:  # no grader files pulled for this run
                return "?"
        status = collections.Counter(exec_status(r) for r, _ in g)
        passed = status.get("OK", 0)
        fails = {k: n for k, n in status.items() if k != "OK"}
        calls = [costs.run_usage(r)["calls"] for r, _ in g if costs.run_usage(r)["calls"]]
        inp = [(t.get("tokens") or {}).get("input") for _, t in g if (t.get("tokens") or {}).get("input")]
        cac = [(t.get("tokens") or {}).get("cache") or 0 for _, t in g if (t.get("tokens") or {}).get("input")]
        mins = [(t.get("seconds") or 0) / 60 for _, t in g if t.get("seconds")]
        f = lambda xs, d=0: f"{st.mean(xs):,.{d}f}" if xs else "-"
        out.append(f"| {v} | {IFC_ALLOWED[v]} | {len(g)} | {passed} of {len(g)} | {st.mean(scores):.3f} | {', '.join(f'{k} {n}' for k, n in sorted(fails.items())) or '-'} "
                   f"| {f(calls, 1)} | {f(inp)} | {f([a - b for a, b in zip(inp, cac)])} | {f(mins, 1)} |")
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="gemini-4-neon")
    ap.add_argument("--write")
    a = ap.parse_args()
    text = table(a.model)
    if a.write:
        pathlib.Path(a.write).write_text(f"# Results by harness version, {a.model}\n\nGenerated by `research/rung_summary.py`; one task (`data-hall-mep-routing`).\n\n{text}\n", encoding="utf-8")
        print("wrote", a.write)
    else:
        print(text)
